use super::*;
use libloading::Library;

type Kernel = unsafe extern "C" fn(
    *const u16,
    *const u16,
    *const i64,
    *const bool,
    usize,
    usize,
    usize,
    f64,
    *mut f32,
    usize,
) -> i32;

#[derive(Debug)]
pub(crate) struct Compiled {
    _library: Library,
    kernel: Kernel,
    names: Vec<String>,
}

impl Compiled {
    pub(crate) fn generate(&self, stream: &EventStream) -> Result<EventFrame, RepresentationError> {
        let (width, height) = stream.sensor_size();
        let len = width
            .checked_mul(height)
            .and_then(|n| n.checked_mul(self.names.len()))
            .filter(|n| *n <= isize::MAX as usize / 4)
            .ok_or(RepresentationError::SizeOverflow)?;
        let mut data = Vec::new();
        data.try_reserve_exact(len)
            .map_err(|_| RepresentationError::SizeOverflow)?;
        data.resize(len, 0.0f32);
        // All columns belong to the borrowed stream; output is exclusively owned here.
        let status = unsafe {
            (self.kernel)(
                stream.xs().as_ptr(),
                stream.ys().as_ptr(),
                stream.ts().as_ptr(),
                stream.ps().as_ptr(),
                stream.len(),
                width,
                height,
                stream.timestamp_scale_ms(),
                data.as_mut_ptr(),
                len,
            )
        };
        if status != 0 {
            return Err(RepresentationError::Device(format!(
                "custom kernel failed (status {status}; 2 = invalid scatter index, 3 = panic)"
            )));
        }
        EventFrame::custom(data, width, height, self.names.clone())
    }
}

#[pyclass(name = "_CustomKernel")]
pub(crate) struct PyCustomKernel {
    pub(crate) inner: Arc<Compiled>,
}

#[pymethods]
impl PyCustomKernel {
    #[new]
    fn new(path: &str, names: Vec<String>) -> PyResult<Self> {
        if names.is_empty() {
            return Err(PyValueError::new_err("channels must be positive"));
        }
        // Only libraries generated by the trusted Python compiler should be supplied here.
        let library =
            unsafe { Library::new(path) }.map_err(|e| PyRuntimeError::new_err(e.to_string()))?;
        let kernel = unsafe {
            *library
                .get::<Kernel>(b"eventcv_kernel_v1\0")
                .map_err(|e| PyRuntimeError::new_err(e.to_string()))?
        };
        Ok(Self {
            inner: Arc::new(Compiled {
                _library: library,
                kernel,
                names,
            }),
        })
    }
    fn __call__(&self, py: Python<'_>, stream: &PyEventStream) -> PyResult<PyEventFrame> {
        let inner = py
            .detach(|| self.inner.generate(&stream.inner))
            .map_err(map_representation_error)?;
        Ok(PyEventFrame { inner })
    }
}
